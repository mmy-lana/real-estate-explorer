type GalleryTuple = readonly [string, string, string, ...string[]];

function propertyImage(photoId: string, width = 1600): string {
  return `${UNSPLASH_ORIGIN}/${photoId}?auto=format&fit=crop&w=${width}&q=80`;
}

function avatarImage(photoId: string, size = 200): string {
  return `${UNSPLASH_ORIGIN}/${photoId}?auto=format&fit=crop&w=${size}&h=${size}&q=80`;
}

/**
 * Deterministic gallery rotation. Offsets are pairwise distinct modulo the pool
 * length, so a single gallery can never show the same photo twice.
 */
function selectGallery(
  seedIndex: number,
  pricePerNight: number,
): GalleryTuple {
  const base = (seedIndex * 7 + 5) % IMAGE_POOL.length;
  const offsets = pricePerNight >= 600 ? [0, 11, 23, 37, 49] : [0, 11, 23, 37];
  const picked = offsets.map(
    (offset) => IMAGE_POOL[(base + offset) % IMAGE_POOL.length],
  );
  const [first, second, third, ...rest] = picked;
  return [first, second, third, ...rest];
}

