/**
 * Verifies repository invariants and returns a list of human-readable issues.
 * An empty array means the repository is safe to render.
 */
export function validateSeedRepository(
  listings: readonly PropertyListing[] = INITIAL_LISTINGS,
): string[] {
  const issues: string[] = [];
  const seenIds = new Set<string>();
  const seenSlugs = new Set<string>();

  if (listings.length < 60) {
    issues.push(
      `expected at least 60 listings, received ${listings.length}`,
    );
  }

  for (const listing of listings) {
    const label = listing.id || "<missing id>";

    if (!isValidListing(listing)) {
      issues.push(`${label}: failed structural validation`);
      continue;
    }

    if (seenIds.has(listing.id)) {
      issues.push(`${label}: duplicate listing id`);
    }
    seenIds.add(listing.id);

    if (seenSlugs.has(listing.slug)) {
      issues.push(`${label}: duplicate slug "${listing.slug}"`);
    }
    seenSlugs.add(listing.slug);

    if (listing.images.length < 3) {
      issues.push(`${label}: gallery must contain at least 3 images`);
    }
    if (new Set(listing.images).size !== listing.images.length) {
      issues.push(`${label}: gallery contains duplicate images`);
    }

    if (listing.pricePerNight < VALIDATION_LIMITS.MIN_PRICE) {
      issues.push(`${label}: nightly price below the minimum`);
    }
    if (listing.amenities.length === 0) {
      issues.push(`${label}: at least one amenity is required`);
    }

    const blockedKeys = new Set<string>();
    for (const range of listing.blockedRanges) {
      const isOrderedIsoRange =
        isIsoDateString(range.startDate) &&
        isIsoDateString(range.endDate) &&
        range.startDate < range.endDate;

      if (!isOrderedIsoRange) {
        issues.push(
          `${label}: invalid blocked range ${range.startDate} → ${range.endDate}`,
        );
        continue;
      }
      const key = `${range.startDate}/${range.endDate}`;
      if (blockedKeys.has(key)) {
        issues.push(`${label}: duplicate blocked range ${key}`);
      }
      blockedKeys.add(key);
    }

    if (!HOSTS_BY_ID.has(listing.host.id)) {
      issues.push(`${label}: host "${listing.host.id}" is not in the roster`);
    }
  }

  return issues;
}

/** Throws when the repository violates any invariant. */
export function assertSeedRepositoryIntegrity(): void {
  const issues = validateSeedRepository();
  if (issues.length > 0) {
    throw new Error(
      `[seed-data] repository integrity check failed:\n- ${issues.join("\n- ")}`,
    );
  }
}
