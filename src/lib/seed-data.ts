const REVIEW_AXIS_BIAS: Record<keyof ReviewBreakdown, number> = {
  cleanliness: 0.02,
  accuracy: 0,
  communication: 0.03,
  location: 0.02,
  checkIn: 0.05,
  value: -0.07,
};

/** Deterministic per-axis review spread around the listing's headline rating. */
function deriveReviewScore(
  baseRating: number,
  axis: keyof ReviewBreakdown,
  listingId: string,
): number {
  const jitter = ((stableHash(`${listingId}:${axis}`) % 17) - 8) / 100;
  return clamp(roundTo(baseRating + REVIEW_AXIS_BIAS[axis] + jitter, 1), 1, 5);
}

function buildReviewBreakdown(
  baseRating: number,
  listingId: string,
): ReviewBreakdown {
  return {
    cleanliness: deriveReviewScore(baseRating, "cleanliness", listingId),
    accuracy: deriveReviewScore(baseRating, "accuracy", listingId),
    communication: deriveReviewScore(baseRating, "communication", listingId),
    location: deriveReviewScore(baseRating, "location", listingId),
    checkIn: deriveReviewScore(baseRating, "checkIn", listingId),
    value: deriveReviewScore(baseRating, "value", listingId),
  };
}

function buildHostProfile(definition: SeedHostDefinition): HostProfile {
  return {
    id: definition.id,
    name: definition.name,
    avatarUrl: avatarImage(definition.avatarPhotoId),
    isSuperhost: definition.isSuperhost,
    joinedDate: definition.joinedDate,
    responseRatePercent: definition.responseRatePercent,
    responseTimeMinutes: definition.responseTimeMinutes,
  };
}

function withTimeOfDay(date: Date, hour: number, minute: number): Date {
  return new Date(date.getTime() + hour * 3_600_000 + minute * 60_000);
}

/** Expands one compact definition into a fully validated `PropertyListing`. */
export function buildListingFromDefinition(
  definition: SeedListingDefinition,
  index: number,
  referenceDate: Date = new Date(),
): PropertyListing {
  const hostDefinition = HOSTS_BY_ID.get(definition.hostId);
  if (!hostDefinition) {
    throw new Error(
      `[seed-data] listing "${definition.id}" references unknown host "${definition.hostId}"`,
    );
  }

  const gallery = (
    definition.images ?? selectGallery(index, definition.pricePerNight)
  ).map((photoId) => propertyImage(photoId));

  const blockedRanges: AvailabilityRange[] = definition.blocked
    .map(([startOffsetDays, endOffsetDays]) => ({
      startDate: toIsoDateString(addDays(referenceDate, startOffsetDays)),
      endDate: toIsoDateString(addDays(referenceDate, endOffsetDays)),
    }))
    .sort((a, b) => a.startDate.localeCompare(b.startDate));

  const createdAt = toIsoDateTimeString(
    withTimeOfDay(
      addDays(referenceDate, -definition.listedDaysAgo),
      8 + (index % 6),
      (index * 7) % 60,
    ),
  );
  const updatedAt = toIsoDateTimeString(
    withTimeOfDay(
      addDays(referenceDate, -definition.updatedDaysAgo),
      9 + (index % 5),
      (index * 11) % 60,
    ),
  );

  return {
    id: definition.id,
    title: definition.title,
    slug: slugify(definition.title),
    description: definition.description,
    propertyType: definition.propertyType,
    pricePerNight: definition.pricePerNight,
    cleaningFee: definition.cleaningFee,
    serviceFeePercent: APP_CONFIG.serviceFeePercent,
    currency: APP_CONFIG.currency,
    ratingAverage: definition.ratingAverage,
    ratingCount: definition.ratingCount,
    reviewBreakdown: buildReviewBreakdown(
      definition.ratingAverage,
      definition.id,
    ),
    images: gallery,
    coordinates: { ...definition.coordinates },
    address: {
      street: definition.street,
      city: definition.city,
      state: definition.state,
      country: definition.country ?? "United States",
      zipCode: definition.zipCode,
      neighborhood: definition.neighborhood,
    },
    capacity: { ...definition.capacity },
    amenities: [...definition.amenities],
    blockedRanges,
    minNights: definition.minNights,
    isInstantBook: definition.isInstantBook,
    isRareFind: definition.isRareFind,
    host: buildHostProfile(hostDefinition),
    createdAt,
    updatedAt,
  };
}

